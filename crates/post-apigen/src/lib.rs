//! Generates the local API's glue from post-core's `#[api]` annotations
//! (docs/phase-1-api.md): the JSON dispatch in post-api, an OpenRPC file, a
//! typed Dart client, and fixtures that hold Rust and Dart to one JSON form.
//!
//! It reads the source with syn and never compiles or depends on the crates
//! it writes for, so it still runs when their generated code is stale or
//! broken. Anything it does not support is an error naming the file, line
//! and column; it never guesses.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

mod emit_dart;
mod emit_rust;
mod emit_schema;
pub mod model;
pub mod names;
pub mod parse;

pub use model::ApiModel;
pub use parse::{Errors, GenError, Source, parse};

/// A core file the generator reads.
pub struct Input {
    /// Relative to the workspace root.
    pub file: &'static str,
    /// The public path of its items in post-core: `""` for the crate root or
    /// items re-exported there.
    pub module: &'static str,
}

/// The core files holding `#[api]` items. Only those items are read.
pub const INPUTS: &[Input] = &[
    Input { file: "crates/post-core/src/lib.rs", module: "" },
    Input { file: "crates/post-core/src/picture.rs", module: "picture" },
    // A private module: its API types are re-exported at the crate root.
    Input { file: "crates/post-core/src/content.rs", module: "" },
];

/// Where `VERSION` is declared, for the OpenRPC file's version.
const VERSION_FILE: &str = "crates/post-api/src/lib.rs";

/// Output paths, relative to the workspace root.
pub mod paths {
    /// Params structs, the method table, `dispatch` and the Rust round trip
    /// of the fixtures, included into post-api.
    pub const DISPATCH: &str = "crates/post-api/src/api.generated.rs";
    /// The API as a reviewable file.
    pub const OPENRPC: &str = "crates/post-api/src/openrpc.generated.json";
    /// One sample JSON value per API type.
    pub const FIXTURES: &str = "crates/post-api/fixtures.generated.json";
    /// The Dart client.
    pub const DART_CLIENT: &str = "app/lib/api/post_api.dart";
    /// The Dart round trip of the fixtures.
    pub const DART_FIXTURES_TEST: &str = "app/test/api_fixtures_test.dart";
}

/// What the outputs say about themselves and how they refer to each other.
pub struct Config {
    /// The first line of every output.
    pub header: String,
    /// The core crate's name in Rust paths.
    pub core_crate: String,
    /// The OpenRPC title.
    pub title: String,
    /// The API version (post-api's `VERSION`).
    pub version: String,
    /// The app's Dart package.
    pub dart_package: String,
    /// The client's path inside the Dart package's `lib/`.
    pub dart_client: String,
    /// What the Dart fixtures test imports for `test` and `expect`.
    pub dart_test_import: String,
    /// The fixtures file as the Dart test (run in `app/`) opens it.
    pub fixtures_from_dart_test: String,
    /// The fixtures file as `include_str!` in `api.generated.rs` names it.
    pub fixtures_from_rust: String,
}

impl Config {
    /// Post's configuration, at API version `version`.
    pub fn new(version: &str) -> Self {
        Self {
            header: "@generated by `cargo run -p post-apigen`. Do not edit.".to_owned(),
            core_crate: "post_core".to_owned(),
            title: "Post local API".to_owned(),
            version: version.to_owned(),
            dart_package: "post".to_owned(),
            dart_client: "api/post_api.dart".to_owned(),
            dart_test_import: "package:flutter_test/flutter_test.dart".to_owned(),
            fixtures_from_dart_test: "../crates/post-api/fixtures.generated.json".to_owned(),
            fixtures_from_rust: "../fixtures.generated.json".to_owned(),
        }
    }
}

/// One generated file.
#[derive(Clone, Debug)]
pub struct Output {
    /// Relative to the workspace root.
    pub path: &'static str,
    /// Its full contents.
    pub contents: String,
}

/// Every output for `model`, types then methods in source order.
pub fn emit(model: &ApiModel, cfg: &Config) -> Vec<Output> {
    vec![
        Output { path: paths::DISPATCH, contents: emit_rust::dispatch(model, cfg) },
        Output { path: paths::OPENRPC, contents: emit_schema::openrpc(model, cfg) },
        Output { path: paths::FIXTURES, contents: emit_schema::fixtures(model, cfg) },
        Output { path: paths::DART_CLIENT, contents: emit_dart::client(model, cfg) },
        Output { path: paths::DART_FIXTURES_TEST, contents: emit_dart::fixtures_test(model, cfg) },
    ]
}

/// Why generation failed.
#[derive(Debug)]
pub enum Failure {
    /// A file could not be read.
    Io(PathBuf, io::Error),
    /// The annotated source has problems.
    Source(Errors),
    /// post-api's `VERSION` was not found.
    NoVersion,
}

impl std::fmt::Display for Failure {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Failure::Io(p, e) => write!(f, "{}: {e}", p.display()),
            Failure::Source(e) => write!(f, "{e}"),
            Failure::NoVersion => write!(f, "{VERSION_FILE}: no `pub const VERSION: &str = \"…\";`"),
        }
    }
}

impl std::error::Error for Failure {}

/// The workspace root, from this crate's place in it.
pub fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn read(root: &Path, file: &str) -> Result<String, Failure> {
    let path = root.join(file);
    fs::read_to_string(&path).map_err(|e| Failure::Io(path, e))
}

/// post-api's `VERSION`, read from its source.
fn version(root: &Path) -> Result<String, Failure> {
    let file = syn::parse_file(&read(root, VERSION_FILE)?).map_err(|_| Failure::NoVersion)?;
    file.items
        .iter()
        .find_map(|item| match item {
            syn::Item::Const(c) if c.ident == "VERSION" => match &*c.expr {
                syn::Expr::Lit(syn::ExprLit { lit: syn::Lit::Str(s), .. }) => Some(s.value()),
                _ => None,
            },
            _ => None,
        })
        .ok_or(Failure::NoVersion)
}

/// Read the real inputs under `root` and generate every output.
pub fn generate(root: &Path) -> Result<Vec<Output>, Failure> {
    let texts = INPUTS.iter().map(|i| read(root, i.file)).collect::<Result<Vec<_>, _>>()?;
    let sources: Vec<Source<'_>> = INPUTS.iter().zip(&texts).map(|(i, text)| Source { path: i.file, module: i.module, text }).collect();
    let model = parse(&sources).map_err(Failure::Source)?;
    Ok(emit(&model, &Config::new(&version(root)?)))
}

/// The outputs whose files under `root` differ from what was generated.
pub fn stale(root: &Path, outputs: &[Output]) -> Vec<&'static str> {
    outputs.iter().filter(|o| fs::read_to_string(root.join(o.path)).ok().as_deref() != Some(o.contents.as_str())).map(|o| o.path).collect()
}

/// Write every output under `root`.
pub fn write(root: &Path, outputs: &[Output]) -> io::Result<()> {
    for o in outputs {
        let path = root.join(o.path);
        if let Some(dir) = path.parent() {
            fs::create_dir_all(dir)?;
        }
        fs::write(path, &o.contents)?;
    }
    Ok(())
}
